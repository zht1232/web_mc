import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';
import { launchOptions } from './lib/browser.mjs';
const out = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../shots/diag');
const b = await chromium.launch(launchOptions());
const ctx = await b.newContext({ viewport: { width: 430, height: 900 }, deviceScaleFactor: 2, hasTouch: true, isMobile: true });
const p = await ctx.newPage();
await p.goto('http://127.0.0.1:5174/?play&touch=1', { waitUntil: 'load' });
await p.waitForFunction(() => !!window.__mc?.running, null, { timeout: 120000 });
await p.waitForTimeout(3000);
await p.screenshot({ path: path.join(out, 'm-inworld.png') });
await p.evaluate(() => window.__mc.screens.open('inventory'));
await p.waitForTimeout(800);
await p.screenshot({ path: path.join(out, 'm-inventory.png') });
await p.evaluate(() => window.__mc.screens.open('creative'));
await p.waitForTimeout(800);
await p.screenshot({ path: path.join(out, 'm-creative.png') });
await b.close();
