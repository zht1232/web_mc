import { chromium } from "playwright";
import { launchOptions } from "./lib/browser.mjs";
const b = await chromium.launch(launchOptions());
const p = await (await b.newContext({ viewport: { width: 1024, height: 640 } })).newPage();
const errors = [];
p.on("pageerror", (e) => errors.push(String(e)));
p.on("console", (m) => { if (m.type() === "error") errors.push(m.text()); });
await p.goto("http://127.0.0.1:5174/?play&perf=0", { waitUntil: "load" });
await p.waitForFunction(() => !!window.__mc?.running, null, { timeout: 120000 });
await p.waitForTimeout(6000);
await p.evaluate(() => { window.__mc.setShaders(true); window.__mc.setRenderScale(0.5); });
await p.waitForTimeout(900);
await p.evaluate(() => window.__mc.setShaders(false));
await p.waitForTimeout(900);
console.log("off", await p.evaluate(() => ({ d: window.__mc.perfDiagnostics().renderTargets, e: window.__mc.gl.getError() })));
await p.screenshot({ path: "shots/_probe-shaders-off.png" });
await p.evaluate(() => window.__mc.setShaders(true));
await p.waitForTimeout(900);
console.log("on", await p.evaluate(() => ({ d: window.__mc.perfDiagnostics().renderTargets, e: window.__mc.gl.getError() })));
await p.screenshot({ path: "shots/_probe-shaders-on.png" });
console.log("errors", errors.slice(0, 5));
await b.close();
