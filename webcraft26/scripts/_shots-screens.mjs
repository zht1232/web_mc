import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';
import { launchOptions } from './lib/browser.mjs';
const root = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(root, '../shots/screens');
const b = await chromium.launch(launchOptions());
const ctx = await b.newContext({ viewport: { width: 1280, height: 720 }, deviceScaleFactor: 1 });
const p = await ctx.newPage();
p.on('pageerror', (e) => console.log('PAGEERROR', String(e).slice(0, 300)));
await p.goto('http://127.0.0.1:5174/', { waitUntil: 'load' });
await p.waitForFunction(() => !!window.__mc?.screens, null, { timeout: 120000 });
await p.waitForTimeout(1500);
async function snap(name) { await p.waitForTimeout(400); await p.screenshot({ path: path.join(out, name + '.png') }); console.log('shot', name); }
await snap('00-title');
await p.evaluate(() => window.__mc.screens.open('selectWorld'));
await snap('01-selectWorld');
await p.evaluate(() => window.__mc.screens.open('createWorld'));
await snap('02-createWorld');
await p.evaluate(() => window.__mc.screens.open('options'));
await snap('03-options');
await p.evaluate(() => window.__mc.screens.open('video'));
await snap('04-video');
await p.evaluate(() => window.__mc.screens.open('controls'));
await snap('05-controls');
await p.evaluate(() => window.__mc.screens.open('language'));
await snap('06-language');
await p.evaluate(() => window.__mc.screens.open('sound'));
await snap('07-sound');
// in-world screens
await p.goto('http://127.0.0.1:5174/?play', { waitUntil: 'load' });
await p.waitForFunction(() => !!window.__mc?.running, null, { timeout: 120000 });
await p.waitForTimeout(2500);
await snap('10-ingame');
await p.evaluate(() => window.__mc.screens.open('pause'));
await snap('11-pause');
await p.evaluate(() => window.__mc.screens.open('inventory'));
await snap('12-inventory');
await p.evaluate(() => window.__mc.screens.open('creative'));
await snap('13-creative');
await p.evaluate(() => window.__mc.screens.open('crafting'));
await snap('14-crafting');
await p.evaluate(() => window.__mc.screens.open('chest'));
await snap('15-chest');
await p.evaluate(() => window.__mc.screens.open('furnace'));
await snap('16-furnace');
await p.evaluate(() => window.__mc.screens.close());
await p.waitForTimeout(300);
await p.keyboard.press('KeyT');
await snap('17-chat');
await p.keyboard.press('Escape');
await p.waitForTimeout(200);
await p.evaluate(() => window.__mc.screens.close());
await p.keyboard.press('F3');
await snap('18-debug');
await b.close();
