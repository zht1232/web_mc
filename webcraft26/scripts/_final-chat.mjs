import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';
import { launchOptions } from './lib/browser.mjs';
const out = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../shots/screens');
const b = await chromium.launch(launchOptions());
const p = await (await b.newContext({ viewport: { width: 1280, height: 720 } })).newPage();
p.on('pageerror', (e) => console.log('ERR', String(e).slice(0, 200)));
await p.goto('http://127.0.0.1:5174/?play', { waitUntil: 'load' });
await p.waitForFunction(() => !!window.__mc?.running, null, { timeout: 120000 });
await p.waitForTimeout(2500);
await p.evaluate(() => { window.__mc.addChatLine('/time set day'); window.__mc.addChatLine('已将时间设置为 1000'); window.__mc.addChatLine('未知指令：/foo'); });
await p.waitForTimeout(500);
await p.screenshot({ path: path.join(out, '30-chat-log.png') });
await b.close();
